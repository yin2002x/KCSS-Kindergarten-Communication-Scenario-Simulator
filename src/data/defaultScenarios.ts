// Helper: Get random scenario for a chosen dimension (avoids repeating the last one if pool > 1)
export function getRandomScenarioForDimension(category: ScenarioCategory, lastId?: string): Scenario {
  const matches = DEFAULT_SCENARIOS.filter((s) => s.category === category);
  if (matches.length === 0) return DEFAULT_SCENARIOS[0];

  const pool = matches.length > 1 && lastId ? matches.filter((s) => s.id !== lastId) : matches;
  const targetPool = pool.length > 0 ? pool : matches;
  const randomIndex = Math.floor(Math.random() * targetPool.length);
  const picked = targetPool[randomIndex];

  return {
    ...picked,
    id: `${picked.id}-${Date.now()}`,
  };
}
